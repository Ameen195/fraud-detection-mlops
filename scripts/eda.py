"""Write docs/EDA.md and docs/img/*.png from data/processed/full.parquet. All numbers computed."""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

df = pd.read_parquet("data/processed/full.parquet")
img = Path("docs/img")
img.mkdir(parents=True, exist_ok=True)
df["day"] = df["TransactionDT"] // 86400
df["week"] = df["day"] // 7
n, rate = len(df), df["isFraud"].mean()


def md(d: pd.DataFrame) -> str:
    cols = list(d.columns)
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    rows += ["| " + " | ".join(str(v) for v in r) + " |" for r in d.itertuples(index=False)]
    return "\n".join(rows)


def by(col: str, top: int = 8) -> pd.DataFrame:
    g = df.groupby(col, observed=True)["isFraud"].agg(rows="size", fraud_rate="mean")
    g = g.sort_values("rows", ascending=False).head(top).reset_index()
    g["fraud_rate"] = (g["fraud_rate"] * 100).round(2).astype(str) + "%"
    return g


weekly = df.groupby("week")["isFraud"].agg(["size", "mean"])
fig, ax = plt.subplots(figsize=(8, 3.5))
ax.plot(weekly.index, weekly["mean"] * 100, marker="o")
for b in ("valid", "test"):
    ax.axvline(df[df.split == b]["week"].min(), color="grey", ls="--")
ax.set(xlabel="week (from first transaction)", ylabel="fraud rate %", title="Fraud rate per week")
fig.tight_layout()
fig.savefig(img / "fraud_rate_weekly.png", dpi=120)

fig, ax = plt.subplots(figsize=(8, 3.5))
for label, g in df.groupby("isFraud"):
    ax.hist(g["TransactionAmt"].clip(upper=500), bins=60, alpha=0.6, density=True,
            label="fraud" if label else "not fraud")
ax.set(xlabel="TransactionAmt (clipped at 500)", ylabel="density", title="Amount distribution")
ax.legend()
fig.tight_layout()
fig.savefig(img / "amount_dist.png", dpi=120)

miss = (df.isna().mean() * 100).sort_values(ascending=False)
miss = miss[miss > 0].head(10).round(1).rename("missing_%").reset_index()
miss.columns = ["column", "missing_%"]
n_cols_50 = int((df.isna().mean() > 0.5).sum())
has_id = df["id_01"].notna()
ident = df.groupby(has_id)["isFraud"].mean() * 100
amt = df.groupby("isFraud")["TransactionAmt"].agg(["mean", "median"]).round(2)
splits = df.groupby("split", observed=True)["isFraud"].agg(rows="size", fraud_rate="mean")
splits["fraud_rate"] = (splits["fraud_rate"] * 100).round(2).astype(str) + "%"
splits = splits.reindex(["train", "valid", "test"]).reset_index()

out = f"""# EDA (auto-generated by `scripts/eda.py`)

Dataset: IEEE-CIS Fraud Detection (card / e-commerce digital payments, not UPI).
`TransactionDT` is seconds from an unknown start; days below are offsets, not calendar dates.

## Overview
- {n:,} transactions, {df.shape[1] - 3} columns (after merge, excl. helper columns), \
fraud rate {rate * 100:.2f}%
- Time span: day {df["day"].min()} to day {df["day"].max()}
- Rows with identity data: {has_id.mean() * 100:.1f}% \
(fraud rate {ident[True]:.2f}% with identity vs {ident[False]:.2f}% without)

## Time-based split (boundaries in `eval/results/split.json`)
{md(splits)}

![weekly](img/fraud_rate_weekly.png)

Dashed lines mark where validation and test start.

## Missing values
{n_cols_50} columns are more than 50% missing. Top 10:

{md(miss)}

## Key patterns
Fraud rate by `ProductCD`:

{md(by("ProductCD"))}

By `card4` (network):

{md(by("card4"))}

By `card6` (type):

{md(by("card6"))}

By `P_emaildomain` (top 8 by volume):

{md(by("P_emaildomain"))}

Amount, fraud vs not (mean / median):

{md(amt.reset_index())}

![amount](img/amount_dist.png)
"""
Path("docs/EDA.md").write_text(out, encoding="utf-8")
print("wrote docs/EDA.md")